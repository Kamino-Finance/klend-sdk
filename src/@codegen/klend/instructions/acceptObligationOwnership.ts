export const DISCRIMINATOR = Buffer.from([249, 130, 70, 176, 151, 187, 239, 6])

export interface AcceptObligationOwnershipAccounts {
  pendingOwner: TransactionSigner
  obligation: Address
  instructionSysvarAccount: Address
}

export function acceptObligationOwnership(
  accounts: AcceptObligationOwnershipAccounts,
  remainingAccounts: Array<AccountMeta | AccountSignerMeta> = [],
  programAddress: Address = PROGRAM_ID
) {
  const keys: Array<AccountMeta | AccountSignerMeta> = [
    {
      address: accounts.pendingOwner.address,
      role: 2,
      signer: accounts.pendingOwner,
    },
    { address: accounts.obligation, role: 1 },
    { address: accounts.instructionSysvarAccount, role: 0 },
    ...remainingAccounts,
  ]
  const data = DISCRIMINATOR
  const ix: Instruction = { accounts: keys, programAddress, data }
  return ix
}
